-- First-party store events contain a random browser ID and no contact details or client IP field.
CREATE TABLE IF NOT EXISTS public.store_analytics_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visitor_id UUID NOT NULL,
  event_type TEXT NOT NULL CHECK (event_type IN ('page_view', 'click', 'product_view', 'add_to_cart', 'checkout_start')),
  path TEXT NOT NULL,
  target TEXT,
  product_slug TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS store_analytics_events_created_at_idx
  ON public.store_analytics_events (created_at DESC);
CREATE INDEX IF NOT EXISTS store_analytics_events_type_created_at_idx
  ON public.store_analytics_events (event_type, created_at DESC);

ALTER TABLE public.store_analytics_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.store_analytics_events FROM anon, authenticated;
GRANT ALL ON TABLE public.store_analytics_events TO service_role;
